def example_sentence(word: str, translation: str, pos: str, category: str) -> str:
    w = word
    templates = {
        "greetings": f"I say \"{w}\" when I meet someone.",
        "food": f"I would like some {w} for lunch.",
        "numbers": f"The answer is {w}.",
        "verbs": f"I {w} every day.",
        "adjectives": f"This is very {w}.",
        "places": f"We go to the {w} on Saturday.",
        "family": f"My {w} lives with us.",
        "work": f"At work we talk about the {w}.",
        "common": f"I use the word \"{w}\" often.",
    }
    if pos == "phrase":
        return f"People say \"{w}\" in daily life."
    if pos == "preposition":
        return f"The book is {w} the table."
    if pos == "conjunction":
        return f"I am tired, {w} I will rest."
    if pos == "determiner":
        return f"{w.capitalize()} student is here."
    if pos == "pronoun":
        return f"{w.capitalize()} are my friend."
    if pos == "interjection":
        return f"She shouted \"{w}!\" happily."
    if pos == "adverb":
        return f"He speaks {w}."
    return templates.get(category, f"This is an example with \"{w}\" ({translation}).")


def build_entries() -> list[dict]:
    raw: list[tuple[str, str, str, str]] = []
    raw.extend(CURATED)
    raw.extend(FOOD)
    raw.extend(VERBS)
    raw.extend(ADJECTIVES)
    raw.extend(PLACES)
    raw.extend(FAMILY)
    raw.extend(WORK)
    raw.extend(COMMON)
    for en, es in NUMBER_CARDINALS:
        raw.append((en, es, "noun", "numbers"))
    for en, es in EXTRA_NUMBERS:
        raw.append((en, es, "noun", "numbers"))

    seen: set[str] = set()
    entries: list[dict] = []
    for word, translation, pos, category in raw:
        key = word.strip().lower()
        if key in seen:
            continue
        seen.add(key)
        if category not in CATEGORIES:
            continue
        entries.append({
            "word": word,
            "translation": translation,
            "partOfSpeech": pos,
            "category": category,
            "exampleSentences": [example_sentence(word, translation, pos, category)],
        })
    return entries


def main() -> int:
    output = DEFAULT_OUTPUT
    if len(sys.argv) > 1:
        output = Path(sys.argv[1])
    entries = build_entries()
    if len(entries) < 500:
        raise SystemExit(f"Expected at least 500 entries, got {len(entries)}")
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8") as f:
        json.dump(entries, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(len(entries))
    return len(entries)


if __name__ == "__main__":
    main()
    sys.exit(0)
